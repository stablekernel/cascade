// TestMergeQueueGeneratorE2E exercises the manifest -> parse -> generate path:
// an opted-in manifest yields a merge_group lane; omitting the block reports the
// generator disabled, so nothing is emitted.
func TestMergeQueueGeneratorE2E(t *testing.T) {
	tmpDir := t.TempDir()
	manifestPath := filepath.Join(tmpDir, "manifest.yaml")

	manifest := `ci:
  config:
    trunk_branch: main
    merge_queue:
      enabled: true
`
	require.NoError(t, os.WriteFile(manifestPath, []byte(manifest), 0644))

	cfg, err := config.ParseWithKey(manifestPath, "ci")
	require.NoError(t, err)

	gen := NewMergeQueueGenerator(cfg, tmpDir)
	require.True(t, gen.Enabled(), "opted-in manifest should enable the merge-queue lane")
	content, err := gen.Generate()
	require.NoError(t, err)
	assert.Contains(t, content, "on:\n  merge_group:")
	assert.Contains(t, content, "cascade --dry-run orchestrate setup")

	// Omitting the block is non-breaking: the generator reports disabled.
	bare := `ci:
  config:
    trunk_branch: main
`
	require.NoError(t, os.WriteFile(manifestPath, []byte(bare), 0644))
	bareCfg, err := config.ParseWithKey(manifestPath, "ci")
	require.NoError(t, err)
	assert.False(t, NewMergeQueueGenerator(bareCfg, tmpDir).Enabled(), "omitted block emits nothing")
}
