// TestExternalWorkflowResolution tests that external workflow paths are correctly
// resolved with refs appended when not specified.
func TestExternalWorkflowResolution(t *testing.T) {
	tests := []struct {
		name         string
		workflow     string
		ref          string
		wantContains string
		description  string
	}{
		{
			name:         "workflow with repo path gets ref appended",
			workflow:     "example/cdk/.github/workflows/deploy.yaml",
			ref:          "main",
			wantContains: "example/cdk/.github/workflows/deploy.yaml@main",
			description:  "External workflow path should have ref appended",
		},
		{
			name:         "workflow already with ref unchanged",
			workflow:     "example/cdk/.github/workflows/deploy.yaml@v1.0.0",
			ref:          "main",
			wantContains: "example/cdk/.github/workflows/deploy.yaml@v1.0.0",
			description:  "Workflow with existing ref should not change",
		},
		{
			name:         "local workflow path uses relative",
			workflow:     ".github/workflows/deploy.yaml",
			ref:          "main",
			wantContains: "./.github/workflows/deploy.yaml",
			description:  "Local workflow should use ./ prefix",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			cfg := &config.TrunkConfig{
				TrunkBranch:  "master",
				Environments: []string{"dev", "prod"},
				Deploys: []config.DeployConfig{
					{Name: "app", Workflow: ".github/workflows/deploy.yaml"},
				},
				External: []config.ExternalRepoConfig{
					{
						Repo: "example/cdk",
						Ref:  tt.ref,
						Deploys: []config.ExternalDeployConfig{
							{Name: "cdk", Workflow: tt.workflow},
						},
					},
				},
			}

			gen := NewPromoteGenerator(cfg, "/tmp")
			content, err := gen.Generate()
			require.NoError(t, err)

			assert.Contains(t, content, tt.wantContains, tt.description)
		})
	}
}

// TestRollbackJobConditions tests that rollback job conditions are correctly
// generated for multi-repo scenarios.
func TestRollbackJobConditions(t *testing.T) {
	cfg := &config.TrunkConfig{
		TrunkBranch:  "master",
		Environments: []string{"dev", "prod"},
		Deploys: []config.DeployConfig{
			{Name: "app", Workflow: ".github/workflows/deploy-app.yaml"},
		},
		External: []config.ExternalRepoConfig{
			{
				Repo: "example/cdk",
				Ref:  "main",
				Deploys: []config.ExternalDeployConfig{
					{Name: "cdk", Workflow: "example/cdk/.github/workflows/deploy.yaml"},
				},
			},
		},
	}

	gen := NewPromoteGenerator(cfg, "/tmp")
	content, err := gen.Generate()
	require.NoError(t, err)

	// Should have rollback for local deploy
	assert.Contains(t, content, "rollback-app:")
	assert.Contains(t, content, "name: Rollback app")

	// Should have rollback for external deploy
	assert.Contains(t, content, "rollback-cdk:")
	assert.Contains(t, content, "name: Rollback cdk (external)")

	// Rollback conditions should check:
	// 1. rollback_on_failure enabled
	// 2. rollback_sha not empty
	// 3. This deploy succeeded
	// 4. At least one deploy failed
	lines := strings.Split(content, "\n")
	inRollbackApp := false
	inRollbackCdk := false
	foundAppCondition := false
	foundCdkCondition := false

	for _, line := range lines {
		if strings.Contains(line, "rollback-app:") {
			inRollbackApp = true
			inRollbackCdk = false
		}
		if strings.Contains(line, "rollback-cdk:") {
			inRollbackApp = false
			inRollbackCdk = true
		}
		if inRollbackApp && strings.Contains(line, "needs.deploy-app.result == 'success'") {
			foundAppCondition = true
		}
		if inRollbackCdk && strings.Contains(line, "needs.deploy-cdk.result == 'success'") {
			foundCdkCondition = true
		}
	}

	assert.True(t, foundAppCondition, "Rollback-app should check deploy-app succeeded")
	assert.True(t, foundCdkCondition, "Rollback-cdk should check deploy-cdk succeeded")

	// Failure detection should include all deploys (local and external)
	assert.Contains(t, content, "needs.deploy-app.result == 'failure'")
	assert.Contains(t, content, "needs.deploy-cdk.result == 'failure'")
}

