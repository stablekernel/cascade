// TestExternalDeployStateTracking tests that preflight correctly identifies
// external deploys that need to run based on state differences.
func TestExternalDeployStateTracking(t *testing.T) {
	// This test covers the integration between config and preflight
	cicdFile := &config.CICDFile{
		Config: &config.TrunkConfig{
			Environments: []string{"dev", "test", "prod"},
			Deploys: []config.DeployConfig{
				{Name: "app"},
			},
			External: []config.ExternalRepoConfig{
				{
					Repo: "example/cdk",
					Ref:  "main",
					Deploys: []config.ExternalDeployConfig{
						{Name: "cdk", Workflow: "example/cdk/.github/workflows/deploy.yaml"},
					},
				},
			},
		},
		State: map[string]*config.EnvState{
			"dev": {
				SHA:     "abc123",
				Version: "v1.0.0-rc.0",
				External: map[string]*config.ExternalDeployState{
					"cdk": {SHA: "cdk-sha-123"},
				},
			},
			"test": {
				SHA:     "def456", // Different from dev
				Version: "v0.9.0",
				External: map[string]*config.ExternalDeployState{
					"cdk": {SHA: "cdk-sha-old"}, // Different from dev
				},
			},
		},
	}

	// Verify config recognizes external deploys
	require.True(t, cicdFile.Config.IsPrimary())
	require.False(t, cicdFile.Config.IsSatellite())

	extDeploy, extRepo := cicdFile.Config.GetExternalDeploy("cdk")
	require.NotNil(t, extDeploy)
	require.NotNil(t, extRepo)
	assert.Equal(t, "cdk", extDeploy.Name)
	assert.Equal(t, "example/cdk", extRepo.Repo)

	allExtDeploys := cicdFile.Config.GetAllExternalDeploys()
	assert.Len(t, allExtDeploys, 1)

	allExtDeployNames := cicdFile.Config.GetAllExternalDeployNames()
	assert.Contains(t, allExtDeployNames, "cdk")

	// Verify external state is tracked
	devState := cicdFile.State["dev"]
	require.NotNil(t, devState.External)
	require.NotNil(t, devState.External["cdk"])
	assert.Equal(t, "cdk-sha-123", devState.External["cdk"].SHA)

	testState := cicdFile.State["test"]
	require.NotNil(t, testState.External)
	require.NotNil(t, testState.External["cdk"])
	assert.Equal(t, "cdk-sha-old", testState.External["cdk"].SHA)
}

