// TestExternalUpdateWorkflow_Generation tests that the external-update workflow
// is correctly generated for primary repos that coordinate satellite deploys.
func TestExternalUpdateWorkflow_Generation(t *testing.T) {
	cfg := &config.TrunkConfig{
		TrunkBranch:  "master",
		Environments: []string{"dev", "test", "prod"},
		External: []config.ExternalRepoConfig{
			{
				Repo: "example/cdk-infra",
				Ref:  "main",
				Deploys: []config.ExternalDeployConfig{
					{Name: "cdk", Workflow: "example/cdk-infra/.github/workflows/deploy.yaml"},
				},
			},
			{
				Repo: "example/k8s-manifests",
				Ref:  "main",
				Deploys: []config.ExternalDeployConfig{
					{Name: "k8s", Workflow: "example/k8s-manifests/.github/workflows/deploy.yaml"},
				},
			},
		},
	}

	gen := NewExternalUpdateGenerator(cfg, "/tmp")
	content, err := gen.Generate()
	require.NoError(t, err)

	// Should have workflow header
	assert.Contains(t, content, "# AUTO-GENERATED by cascade")
	assert.Contains(t, content, "name: External Update")

	// Should have workflow_dispatch trigger with inputs for external updates
	assert.Contains(t, content, "workflow_dispatch:")
	assert.Contains(t, content, "inputs:")

	// Should accept deploy info as inputs
	assert.Contains(t, content, "source_repo")
	assert.Contains(t, content, "deploy_name")
	assert.Contains(t, content, "environment")
	assert.Contains(t, content, "sha")

	// Should call the external update CLI command
	assert.Contains(t, content, "cascade external update")
	assert.Contains(t, content, "--source-repo")
	assert.Contains(t, content, "--deploy-name")
	assert.Contains(t, content, "--environment")
	assert.Contains(t, content, "--sha")

	// Should configure a git identity before the verb runs. `cascade external
	// update` commits and pushes the manifest state via git, which aborts on a
	// clean runner with no identity, so the workflow must set one first.
	assert.Contains(t, content, "Configure Git")
	assert.Contains(t, content, "git config user.name")
	assert.Contains(t, content, "git config user.email")
	assert.Less(t, strings.Index(content, "Configure Git"),
		strings.Index(content, "cascade external update"),
		"git identity must be configured before the update verb commits")
}

