// mockWorkflowContent returns a minimal workflow YAML that the generator can parse
const mockWorkflowContent = `name: Mock Deploy
on:
  workflow_call:
    inputs:
      environment:
        type: string
        required: true
    outputs:
      deployed_sha:
        value: ${{ jobs.deploy.outputs.sha }}
jobs:
  deploy:
    runs-on: ubuntu-latest
    outputs:
      sha: ${{ github.sha }}
    steps:
      - run: echo "deploying"
`

// createMockWorkflow creates a mock workflow file in a temp directory
func createMockWorkflow(t *testing.T, baseDir, workflowPath string) {
	t.Helper()
	fullPath := filepath.Join(baseDir, workflowPath)
	err := os.MkdirAll(filepath.Dir(fullPath), 0755)
	require.NoError(t, err)
	err = os.WriteFile(fullPath, []byte(mockWorkflowContent), 0644)
	require.NoError(t, err)
}

